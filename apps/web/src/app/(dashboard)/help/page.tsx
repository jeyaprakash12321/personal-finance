"use client";

import {
  BookOpen,
  CircleHelp,
  Mail,
  MessageCircle,
  Search,
  ShieldCheck,
  Sparkles,
} from "lucide-react";
import { useMemo, useState } from "react";

const faqs = [
  {
    question: "How do I add a transaction?",
    answer:
      "Open Transactions from the sidebar and select Add Transaction. Choose your account, category, amount, type, and transaction date, then save it.",
  },
  {
    question: "How are account balances calculated?",
    answer:
      "Wealthly starts with the account's initial balance and then applies recorded income and expense transactions to calculate the current balance.",
  },
  {
    question: "How does budgeting work?",
    answer:
      "Create a monthly budget for an expense category. Wealthly compares the budget with transactions recorded for that category during the selected month.",
  },
  {
    question: "How do goals work?",
    answer:
      "Create a goal with a target amount and optional target date. You can then add contributions and track your progress toward the target.",
  },
  {
    question: "Where do Reports get their data?",
    answer:
      "Reports use your recorded transactions and the cash-flow information generated by Wealthly's financial data layer.",
  },
  {
    question: "Can I change my currency?",
    answer:
      "The currency preference is available in Settings. Currency persistence will be connected to your account profile when authentication and user preferences are added.",
  },
];

export default function HelpPage() {
  const [search, setSearch] = useState("");
  const [openQuestion, setOpenQuestion] =
    useState<string | null>(null);

  const filteredFaqs = useMemo(() => {
    const query = search.trim().toLowerCase();

    if (!query) {
      return faqs;
    }

    return faqs.filter(
      (faq) =>
        faq.question.toLowerCase().includes(query) ||
        faq.answer.toLowerCase().includes(query)
    );
  }, [search]);

  return (
    <div className="min-h-screen px-5 py-6 sm:px-8 lg:px-10">
      <div className="mx-auto max-w-[1100px]">
        {/* Header */}
        <div className="text-center">
          <div className="mx-auto flex h-11 w-11 items-center justify-center rounded-2xl bg-[#dff6ea] text-[#078653]">
            <CircleHelp className="h-5 w-5" />
          </div>

          <p className="mt-4 text-[11px] font-semibold uppercase tracking-[0.14em] text-[#16a36a]">
            Support center
          </p>

          <h1 className="mt-2 text-[30px] font-bold tracking-[-0.04em] text-[#10231c] sm:text-[36px]">
            How can we help?
          </h1>

          <p className="mx-auto mt-2 max-w-xl text-sm leading-6 text-[#71817a]">
            Find answers about accounts, transactions, budgets,
            goals, and everything else inside Wealthly.
          </p>
        </div>

        {/* Search */}
        <div className="mx-auto mt-7 max-w-2xl">
          <div className="relative">
            <Search className="absolute left-4 top-1/2 h-4 w-4 -translate-y-1/2 text-[#91a09a]" />

            <input
              value={search}
              onChange={(event) =>
                setSearch(event.target.value)
              }
              placeholder="Search for an answer..."
              className="w-full rounded-2xl border border-[#dfe8e2] bg-white py-4 pl-11 pr-4 text-sm text-[#30453c] shadow-[0_8px_30px_rgba(16,35,28,0.05)] outline-none transition placeholder:text-[#a0ada7] focus:border-[#a9dec3]"
            />
          </div>
        </div>

        {/* Quick links */}
        <div className="mt-8 grid gap-4 sm:grid-cols-3">
          <HelpCard
            icon={<BookOpen className="h-5 w-5" />}
            title="Getting started"
            description="Learn the basics of tracking your money."
          />

          <HelpCard
            icon={<MessageCircle className="h-5 w-5" />}
            title="Financial features"
            description="Understand budgets, goals, and reports."
          />

          <HelpCard
            icon={<ShieldCheck className="h-5 w-5" />}
            title="Privacy & security"
            description="Learn how account security will work."
          />
        </div>

        {/* FAQ */}
        <section className="mt-8 rounded-2xl border border-[#e4ebe7] bg-white p-5 shadow-[0_8px_30px_rgba(16,35,28,0.04)] sm:p-6">
          <div className="flex items-start justify-between gap-4">
            <div>
              <h2 className="text-[18px] font-bold tracking-[-0.02em] text-[#10231c]">
                Frequently asked questions
              </h2>

              <p className="mt-1 text-sm text-[#82908a]">
                Quick answers to common questions.
              </p>
            </div>

            <span className="hidden rounded-full bg-[#f1f8f4] px-3 py-1.5 text-[11px] font-semibold text-[#60736b] sm:block">
              {filteredFaqs.length} articles
            </span>
          </div>

          <div className="mt-6 divide-y divide-[#edf1ef]">
            {filteredFaqs.length === 0 ? (
              <div className="py-10 text-center">
                <p className="text-sm font-semibold text-[#60736b]">
                  No matching answers
                </p>

                <p className="mt-1 text-xs text-[#a0ada7]">
                  Try searching for another topic.
                </p>
              </div>
            ) : (
              filteredFaqs.map((faq) => {
                const isOpen =
                  openQuestion === faq.question;

                return (
                  <div key={faq.question}>
                    <button
                      type="button"
                      onClick={() =>
                        setOpenQuestion(
                          isOpen ? null : faq.question
                        )
                      }
                      className="flex w-full items-center justify-between gap-5 py-5 text-left"
                    >
                      <span className="text-sm font-semibold text-[#30453c]">
                        {faq.question}
                      </span>

                      <span
                        className={`flex h-7 w-7 shrink-0 items-center justify-center rounded-full bg-[#f1f8f4] text-[#078653] transition ${
                          isOpen ? "rotate-45" : ""
                        }`}
                      >
                        <span className="text-lg font-light leading-none">
                          +
                        </span>
                      </span>
                    </button>

                    {isOpen && (
                      <div className="pb-5 pr-10">
                        <p className="text-sm leading-6 text-[#71817a]">
                          {faq.answer}
                        </p>
                      </div>
                    )}
                  </div>
                );
              })
            )}
          </div>
        </section>

        {/* Contact */}
        <section className="mt-6 overflow-hidden rounded-2xl border border-[#cceedd] bg-[#effaf4] p-6 sm:p-7">
          <div className="flex flex-col gap-6 md:flex-row md:items-center md:justify-between">
            <div className="flex items-start gap-4">
              <div className="flex h-11 w-11 shrink-0 items-center justify-center rounded-xl bg-white text-[#16a36a] shadow-sm">
                <Mail className="h-5 w-5" />
              </div>

              <div>
                <p className="text-[16px] font-bold text-[#10231c]">
                  Still need help?
                </p>

                <p className="mt-1 max-w-lg text-sm leading-6 text-[#60736b]">
                  Support messaging will be connected as Wealthly&apos;s
                  account and notification system is completed.
                </p>
              </div>
            </div>

            <button
              type="button"
              disabled
              className="flex shrink-0 items-center justify-center gap-2 rounded-xl bg-white px-5 py-3 text-sm font-semibold text-[#078653] opacity-70 shadow-sm"
            >
              <Mail className="h-4 w-4" />
              Contact support
            </button>
          </div>
        </section>

        {/* Footer note */}
        <div className="flex items-center justify-center gap-2 py-8 text-xs text-[#a0ada7]">
          <Sparkles className="h-3.5 w-3.5" />
          <span>Small steps. Bigger tomorrows.</span>
        </div>
      </div>
    </div>
  );
}

function HelpCard({
  icon,
  title,
  description,
}: {
  icon: React.ReactNode;
  title: string;
  description: string;
}) {
  return (
    <button
      type="button"
      className="rounded-2xl border border-[#e4ebe7] bg-white p-5 text-left shadow-[0_8px_30px_rgba(16,35,28,0.035)] transition hover:-translate-y-0.5 hover:shadow-[0_12px_30px_rgba(16,35,28,0.07)]"
    >
      <div className="flex h-10 w-10 items-center justify-center rounded-xl bg-[#ecfdf5] text-[#16a36a]">
        {icon}
      </div>

      <h3 className="mt-4 text-sm font-bold text-[#30453c]">
        {title}
      </h3>

      <p className="mt-1 text-xs leading-5 text-[#82908a]">
        {description}
      </p>
    </button>
  );
}
